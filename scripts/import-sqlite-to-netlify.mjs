function fallbackMetaRows() {
  if (dump.cms_meta_localized?.length) {
    return dump.cms_meta_localized;
  }

  return (dump.cms_meta ?? []).map((row) => ({
    locale: "en",
    bride_name: row.bride_name,
    groom_name: row.groom_name,
    event_date: row.event_date,
    event_location: row.event_location,
    hero_headline: row.hero_headline,
    hero_subtext: row.hero_subtext,
    brand_text: row.brand_text,
    updated_at: row.updated_at,
  }));
}

function toTimestamp(value) {
  if (!value) {
    return null;
  }

  return String(value).includes("T") ? value : `${value}Z`;
}

async function syncSequences() {
  for (const [table, column] of [
    ["rsvps", "id"],
    ["cms_menu_items", "id"],
    ["cms_blocks", "id"],
    ["cms_media", "id"],
    ["invitees", "id"],
  ]) {
    await sql.query(
      `SELECT setval(pg_get_serial_sequence($1, $2), COALESCE((SELECT MAX(${column}) FROM ${table}), 1), true)`,
      [table, column]
    );
  }
}
