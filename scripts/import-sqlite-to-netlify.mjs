import { spawnSync } from "node:child_process";
import { existsSync } from "node:fs";
import { resolve } from "node:path";

import { neon } from "@netlify/neon";

const args = new Set(process.argv.slice(2));
const replace = args.has("--replace");
const sqlitePathArg = process.argv.slice(2).find((arg) => !arg.startsWith("--")) ?? "data/rsvps.sqlite";
const sqlitePath = resolve(sqlitePathArg);

if (!process.env.NETLIFY_DATABASE_URL) {
  console.error("Missing NETLIFY_DATABASE_URL. Run `netlify db init`, then run this command with the env loaded.");
  process.exit(1);
}

if (!existsSync(sqlitePath)) {
  console.error(`SQLite file not found: ${sqlitePath}`);
  process.exit(1);
}

const sql = neon();

const TABLES = [
  "cms_media_collections",
  "cms_meta_localized",
  "cms_couple_section",
  "cms_event_section",
  "cms_menu_items",
  "cms_blocks",
  "cms_media",
  "invitees",
  "rsvps",
];

const dump = readSqliteDump(sqlitePath);

await createSchema();

if (replace) {
  await sql.query(
    `TRUNCATE TABLE ${[
      "rsvps",
      "invitees",
      "cms_media",
      "cms_blocks",
      "cms_menu_items",
      "cms_event_section",
      "cms_couple_section",
      "cms_meta_localized",
      "cms_media_collections",
    ].join(", ")} RESTART IDENTITY`
  );
}

await importRows();
await syncSequences();

console.log("Import complete.");
for (const table of TABLES) {
  console.log(`${table}: ${dump[table]?.length ?? 0}`);
}

function readSqliteDump(path) {
  const python = spawnSync(
    "python3",
    [
      "-",
      path,
      ...TABLES,
      "cms_meta",
    ],
    {
      encoding: "utf8",
      input: String.raw`
import json
import sqlite3
import sys

db_path = sys.argv[1]
tables = sys.argv[2:]
conn = sqlite3.connect(db_path)
conn.row_factory = sqlite3.Row
out = {}
existing = {row["name"] for row in conn.execute("SELECT name FROM sqlite_master WHERE type='table'")}

for table in tables:
    if table not in existing:
        out[table] = []
        continue
    rows = conn.execute(f"SELECT * FROM {table}").fetchall()
    out[table] = [dict(row) for row in rows]

conn.close()
print(json.dumps(out))
`,
    }
  );

  if (python.status !== 0) {
    console.error(python.stderr || python.stdout);
    process.exit(python.status ?? 1);
  }

  return JSON.parse(python.stdout);
}

async function createSchema() {
  await sql`
    CREATE TABLE IF NOT EXISTS rsvps (
      id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
      name TEXT NOT NULL,
      email TEXT NOT NULL DEFAULT '',
      phone TEXT,
      attending INTEGER NOT NULL,
      guest_count INTEGER NOT NULL,
      what TEXT,
      meal TEXT,
      created_at TIMESTAMPTZ NOT NULL DEFAULT now()
    )
  `;

  await sql`
    CREATE TABLE IF NOT EXISTS cms_menu_items (
      id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
      label TEXT NOT NULL,
      href TEXT NOT NULL,
      position INTEGER NOT NULL DEFAULT 0,
      is_visible INTEGER NOT NULL DEFAULT 1,
      locale TEXT NOT NULL DEFAULT 'en',
      UNIQUE(label, href, locale)
    )
  `;

  await sql`
    CREATE TABLE IF NOT EXISTS cms_blocks (
      id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
      slug TEXT NOT NULL,
      selector TEXT NOT NULL,
      content_html TEXT NOT NULL,
      position INTEGER NOT NULL DEFAULT 0,
      is_visible INTEGER NOT NULL DEFAULT 1,
      locale TEXT NOT NULL DEFAULT 'en',
      updated_at TIMESTAMPTZ NOT NULL DEFAULT now(),
      UNIQUE(slug, locale)
    )
  `;

  await sql`
    CREATE TABLE IF NOT EXISTS cms_meta_localized (
      locale TEXT PRIMARY KEY,
      bride_name TEXT NOT NULL,
      groom_name TEXT NOT NULL,
      event_date TEXT,
      event_location TEXT,
      hero_headline TEXT,
      hero_subtext TEXT,
      brand_text TEXT,
      updated_at TIMESTAMPTZ NOT NULL DEFAULT now()
    )
  `;

  await sql`
    CREATE TABLE IF NOT EXISTS cms_couple_section (
      locale TEXT PRIMARY KEY,
      left_name TEXT NOT NULL,
      left_bio TEXT,
      left_icon_url TEXT,
      left_facebook_url TEXT,
      left_twitter_url TEXT,
      left_instagram_url TEXT,
      right_name TEXT NOT NULL,
      right_bio TEXT,
      right_icon_url TEXT,
      right_facebook_url TEXT,
      right_twitter_url TEXT,
      right_instagram_url TEXT,
      center_photo_url TEXT,
      center_overlay_url TEXT,
      updated_at TIMESTAMPTZ NOT NULL DEFAULT now()
    )
  `;

  await sql`
    CREATE TABLE IF NOT EXISTS cms_event_section (
      locale TEXT PRIMARY KEY,
      eyebrow TEXT NOT NULL,
      heading TEXT NOT NULL,
      items_json TEXT NOT NULL,
      updated_at TIMESTAMPTZ NOT NULL DEFAULT now()
    )
  `;

  await sql`
    CREATE TABLE IF NOT EXISTS cms_media (
      id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
      collection TEXT NOT NULL,
      image_url TEXT NOT NULL,
      title TEXT,
      description TEXT,
      link_url TEXT,
      position INTEGER NOT NULL DEFAULT 0,
      locale TEXT NOT NULL DEFAULT 'en',
      created_at TIMESTAMPTZ NOT NULL DEFAULT now(),
      updated_at TIMESTAMPTZ NOT NULL DEFAULT now()
    )
  `;

  await sql`
    CREATE TABLE IF NOT EXISTS invitees (
      id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
      first_name TEXT,
      last_name TEXT,
      email TEXT,
      phone TEXT,
      locale TEXT NOT NULL DEFAULT 'en',
      invite_code TEXT NOT NULL UNIQUE,
      status TEXT NOT NULL DEFAULT 'pending',
      attending INTEGER,
      guest_count INTEGER,
      response_note TEXT,
      responded_at TIMESTAMPTZ,
      created_at TIMESTAMPTZ NOT NULL DEFAULT now(),
      updated_at TIMESTAMPTZ NOT NULL DEFAULT now()
    )
  `;

  await sql`
    CREATE TABLE IF NOT EXISTS cms_media_collections (
      collection TEXT PRIMARY KEY,
      label TEXT NOT NULL
    )
  `;
}

